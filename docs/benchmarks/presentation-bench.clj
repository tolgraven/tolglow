(require '[afterglow.render.frame :as f] '[afterglow.render.presentation :as p])
(def fixtures (vec (for [u (range 100) head (range 128)] {:id [u head] :universe u :address (inc (* head 4)) :channels {:red 1 :green 2 :blue 3 :white 4}})))
(def plan (p/compile-plan fixtures))
(def raw {:universes (into {} (for [u (range 100)] [u (byte-array (repeat 512 (unchecked-byte 200)))]))})
(def metadata {:epoch 0 :frame-id 0 :time-ms 0 :completed-at-ms 0})
(def frozen (p/freeze-frame metadata raw))
(def states (into {} (for [mode [:direct :hold-fade :buffered-interpolation]] [mode (:state (p/complete (p/new-state plan {:mode mode}) frozen))])))
(def two (:state (p/complete (get states :buffered-interpolation) (assoc frozen :frame-id 1 :time-ms 25 :completed-at-ms 25))))
(def bean (java.lang.management.ManagementFactory/getThreadMXBean))
(defn measure [run]
  (dotimes [_ 30] (run))
  (let [id (.getId (Thread/currentThread))
        before (.getThreadAllocatedBytes ^com.sun.management.ThreadMXBean bean id)
        samples (vec (for [_ (range 100)] (let [start (System/nanoTime)] (run) (/ (- (System/nanoTime) start) 1e6))))
        allocated (- (.getThreadAllocatedBytes ^com.sun.management.ThreadMXBean bean id) before)
        ordered (vec (sort samples))]
    {:samples 100 :warmup 30 :p50-ms (nth ordered 49) :p95-ms (nth ordered 94) :p99-ms (nth ordered 98) :max-ms (peek ordered) :allocated-bytes-per-call (/ allocated 100.0)}))
(def result {:recorded-at "2026-11-21" :universes 100 :bytes-per-frame 51200 :fixtures 12800 :java (System/getProperty "java.version") :scope "In-process immutable policy only. No engine, transport, scheduler or network. Single thread; pauses/GC included."
             :freeze (measure #(p/freeze-frame metadata raw))
             :complete (measure #(p/complete (p/new-state plan) frozen))
             :direct (measure #(p/present (get states :direct) 75))
             :fade (measure #(p/present (get states :hold-fade) 75))
             :interpolation (measure #(p/present two 37.5))
             :materialize (measure #(p/materialize frozen))})
(prn result)
